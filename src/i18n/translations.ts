if (typeof import.meta !== 'undefined' && import.meta.env?.DEV) {
  const enKeys = Object.keys(en) as TranslationKey[];
  const zhKeys = Object.keys(zh) as TranslationKey[];
  for (const k of enKeys) {
    if (!zh[k]) {
      console.warn(`[i18n] Missing Chinese translation for key: "${k}"`);
    }
  }
  for (const k of zhKeys) {
    if (!en[k]) {
      console.warn(`[i18n] Missing English translation for key: "${k}"`);
    }
  }
}

export function t(
  lang: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>
): string {
  const table = lang === 'zh' ? zh : en;
  let value = table[key];
  if (value === undefined || value === '') {
    if (typeof import.meta !== 'undefined' && import.meta.env?.DEV) {
      console.warn(`[i18n] Missing translation for key "${key}" in language "${lang}"`);
    }
    value = en[key] ?? key;
  }
  if (vars) {
    for (const [varKey, varVal] of Object.entries(vars)) {
      value = value.replace(new RegExp(`\\{${varKey}\\}`, 'g'), String(varVal));
    }
  }
  return value;
}

