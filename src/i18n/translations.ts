export function formatPHP(amount: number): string {
  return '₱' + Math.round(amount).toLocaleString('en-PH');
}

export function formatDate(dateStr: string, lang: Language): string {
  if (!dateStr) return '';
  const match = dateStr.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (!match) return dateStr;
  const [, year, month, day] = match;
  if (lang === 'zh') {
    return `${year}年${Number(month)}月${Number(day)}日`;
  }
  return dateStr;
}

export function formatTimestamp(ts: string, lang: Language): string {
  if (!ts) return '';
  if (lang === 'en') return ts;
  const match = ts.match(/^(\d{4})-(\d{2})-(\d{2})(?:\s+(\d{2}:\d{2}))?/);
  if (!match) return ts;
  const [, year, month, day, time] = match;
  return `${year}年${Number(month)}月${Number(day)}日${time ? ` ${time}` : ''}`;
}

export function formatDimensions(dims: string, lang: Language): string {
  if (lang === 'en') return dims;
  return dims.replace(/\bcm\b/gi, '厘米');
}
